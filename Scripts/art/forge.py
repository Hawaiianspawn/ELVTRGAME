def selftest():
    import tempfile
    # composition is deterministic and adds no palette clause
    a = compose("A shinobi, narrow and wrapped.")
    assert a == compose("A shinobi, narrow and wrapped"), a
    assert a.endswith(TAIL), a
    assert "palette exactly" in a and "#" not in a, a
    assert compose("x", tail="") == "x."

    # the slug rule is the whole fix for the account's 135 prompt-named states
    for good in ("turret-nest", "v2", "hazmat-bulk-3"):
        assert check_slug(good) == good
    for bad in ("Can you make a Turre", "Turret_Nest", "", "trailing-", "UPPER"):
        try:
            check_slug(bad)
            raise AssertionError("accepted bad slug %r" % bad)
        except Fail:
            pass

    # verdict round-trips without touching judge's own verdict key, carries the recipe,
    # and never rewrites family.json (whose compact hand-authored arrays a json.dump
    # would explode into a ~200-line diff around one real change)
    with tempfile.TemporaryDirectory() as td:
        fam = "forge-selftest"
        real_fam, real_ren = vp.FAMILIES, vp.RENDERS
        try:
            vp.FAMILIES, vp.RENDERS = Path(td) / "fam", Path(td) / "ren"
            spec = {"family": fam, "axis": {"name": "aspect", "description": "d"},
                    "constant": "c", "variants": [{"slug": "old"}]}
            vp.save_json(vp.spec_path(fam), spec)
            before = vp.spec_path(fam).read_text(encoding="utf-8")
            vp.save_json(vp.manifest_path(fam), {
                "family": fam,
                "variants": {"a": {"verdict": "reject", "reasons": ["r"], "measured": {}}}})
            save_jobs(fam, {"a": {"slug": "a", "base_id": "B", "character_id": "C",
                                  "prompt": "a shinobi. " + TAIL, "seed": None,
                                  "status": "done"}})

            set_verdict(fam, "a", "approve", "reads best in a crowd")
            m = vp.load_manifest(fam)
            assert m["variants"]["a"]["verdict"] == "reject"          # judge's, untouched
            assert m["variants"]["a"]["owner"]["verdict"] == "approve"
            assert m["variants"]["a"]["owner"]["shipped"] is None
            assert m["variants"]["a"]["owner"]["generated"]["base_id"] == "B"
            assert vp.spec_path(fam).read_text(encoding="utf-8") == before, \
                "approve must not rewrite family.json"
            assert '"slug": "a"' in spec_line(fam, "a")

            # deny records a verdict and no recipe, and moves nothing on disk
            set_verdict(fam, "a", "deny")
            assert "generated" in vp.load_manifest(fam)["variants"]["a"]["owner"]
            set_verdict(fam, "a", "clear")
            assert "owner" not in vp.load_manifest(fam)["variants"]["a"]
            assert spec_line(fam, "a") is None
        finally:
            vp.FAMILIES, vp.RENDERS = real_fam, real_ren

    # a refine names its parent, survives a legacy name, and never collides
    with tempfile.TemporaryDirectory() as td:
        fam = "forge-refine"
        real_fam, real_ren = vp.FAMILIES, vp.RENDERS
        try:
            vp.FAMILIES, vp.RENDERS = Path(td) / "fam", Path(td) / "ren"
            assert slugify("Can_you_make_a_Turre") == "can-you-make-a-turre"
            assert slugify("!!!") == "variant"
            # the three id sources, in priority order
            vp.save_json(vp.spec_path(fam), {
                "family": fam, "axis": {"name": "a", "description": "d"}, "constant": "c",
                "variants": [{"slug": "x"}],
                "naming": {"map": [{"folder": "Legacy_Name", "state_id": "FROM-MAP"}]}})
            vp.save_json(vp.RENDERS / fam / "source.json",
                         {"state_ids": {"Other_One": "FROM-SOURCE"}})
            save_jobs(fam, {"forged": {"slug": "forged", "character_id": "FROM-JOB",
                                       "status": "done"}})
            assert character_id_of(fam, "forged") == "FROM-JOB"
            assert character_id_of(fam, "Legacy_Name") == "FROM-MAP"
            assert character_id_of(fam, "Other_One") == "FROM-SOURCE"
            try:
                character_id_of(fam, "nobody")
                raise AssertionError("refined a variant with no recorded id")
            except Fail:
                pass
            # -r2 first, and a refine of a refine keeps counting on the same stem
            assert next_refine_slug(fam, "Legacy_Name") == "legacy-name-r2"
            save_jobs(fam, {**load_jobs(fam), "forged-r2": {"slug": "forged-r2"}})
            assert next_refine_slug(fam, "forged") == "forged-r3"
            assert next_refine_slug(fam, "forged-r2") == "forged-r3"
            assert check_slug(next_refine_slug(fam, "Can_you_make_a_Turre"))
        finally:
            vp.FAMILIES, vp.RENDERS = real_fam, real_ren

    # selects: a hand-made dir seeds as approved, approve copies, deny parks (never deletes),
    # clear forgets, and Renders is never written
    with tempfile.TemporaryDirectory() as td:
        global SELECTS
        real_fam, real_ren, real_sel = vp.FAMILIES, vp.RENDERS, SELECTS
        try:
            vp.FAMILIES, vp.RENDERS, SELECTS = Path(td) / "fam", Path(td) / "ren", Path(td) / "sel"
            def rot(fam, slug):
                d = vp.RENDERS / fam / "raw" / slug / "rotations"
                d.mkdir(parents=True)
                for n in ("south", "north"):
                    (d / ("%s.png" % n)).write_bytes(b"png")
                return d
            rot("famA", "look1"); rot("famA", "look2")
            hand = SELECTS / "Human Soldier Branch" / "look2" / "rotations"
            hand.mkdir(parents=True); (hand / "south.png").write_bytes(b"png")
            (hand.parent / "edit.aseprite").write_bytes(b"ase")

            rec = selects_seed(selects_load(), selects_candidates())
            assert rec["famA/look2"]["verdict"] == "approve" and rec["famA/look2"]["seeded"]
            assert rec["famA/look2"]["branch"] == "Human Soldier Branch"

            set_select("famA/look1", "approve", "Elf Branch")
            assert (SELECTS / "Elf Branch" / "look1" / "rotations" / "north.png").exists()
            assert selects_load()["famA/look1"]["branch"] == "Elf Branch"
            try:
                set_select("famA/look1", "approve", "")
                raise AssertionError("approved with no branch")
            except Fail:
                pass

            set_select("famA/look2", "deny")
            assert not (SELECTS / "Human Soldier Branch" / "look2").exists()
            assert (SELECTS / "_denied" / "look2" / "edit.aseprite").exists(), "deny must not delete"
            assert selects_load()["famA/look2"]["verdict"] == "deny"
            assert (vp.RENDERS / "famA" / "raw" / "look2" / "rotations" / "south.png").exists()
            assert "_denied" not in selects_branches()
            html = official_page()
            assert "look1" in html and "look2" not in html, "official page must list approved only"

            set_select("famA/look1", "clear")
            assert "famA/look1" not in selects_load()
            assert not (SELECTS / "Elf Branch" / "look1").exists()
            assert not (vp.FAMILIES / "famA").exists(), "no manifest for a family with no spec"
        finally:
            vp.FAMILIES, vp.RENDERS, SELECTS = real_fam, real_ren, real_sel

    # nearest-neighbour is on band midpoints, and a variant with no band is not compared
    bands = {"x": {"aspect": [1.0, 1.0], "solidity": [.5, .5], "asymmetry": [.1, .1]},
             "y": {"aspect": [1.1, 1.1], "solidity": [.5, .5], "asymmetry": [.1, .1]},
             "z": {"aspect": [3.0, 3.0], "solidity": [.9, .9], "asymmetry": [.4, .4]},
             "w": {"missing": 3}}
    n, d = nearest_sibling(bands, "x")
    assert n == "y" and abs(d - 0.1) < 1e-9, (n, d)
    assert nearest_sibling(bands, "x", only={"z"})[0] == "z"
    assert nearest_sibling(bands, "w") == (None, None)

    print("forge selftest OK")
    return 0


