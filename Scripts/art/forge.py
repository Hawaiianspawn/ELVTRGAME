def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--family", default="pathfinder-line")
    ap.add_argument("--atlas", default=None, help="composite request id to ship into")
    ap.add_argument("--prefix", default=None, help="atlas prefix, e.g. archer-")
    ap.add_argument("--port", type=int, default=8770)
    ap.add_argument("--scale", type=int, default=3)
    ap.add_argument("--no-open", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()

    if args.selftest:
        return selftest()

    fb = forge_block(args.family)
    atlas = args.atlas or fb.get("atlas")
    prefix = args.prefix or fb.get("prefix")

    import uvicorn
    url = "http://127.0.0.1:%d/" % args.port
    print("forge  family=%s  atlas=%s  prefix=%s\n%s"
          % (args.family, atlas or "-", prefix or "-", url))
    if not args.no_open:
        webbrowser.open(url)
    uvicorn.run(build_app(args.family, atlas, prefix, args.scale),
                host="127.0.0.1", port=args.port, log_level="warning")
    return 0


