def build_app(family, atlas, prefix, scale):
    from fastapi import FastAPI, HTTPException
    from fastapi.responses import HTMLResponse, JSONResponse, Response

    app = FastAPI(title="Sprite Forge")

    def guard(fn, *a, **kw):
        try:
            return fn(*a, **kw)
        except Fail as e:
            raise HTTPException(status_code=400, detail=str(e))

    @app.get("/", response_class=HTMLResponse)
    def index():
        return roster_page()

    @app.get("/family/{fam}", response_class=HTMLResponse)
    def family_view(fam: str):
        # A family's own forge block is authoritative; the CLI flags only stand in for the
        # family the server was started on, so browsing to another one cannot ship it into
        # the wrong atlas by inheriting the wrong prefix.
        fb = forge_block(fam)
        return page(fam,
                    fb.get("atlas") or (atlas if fam == family else None),
                    fb.get("prefix") or (prefix if fam == family else None), scale)

    @app.get("/selects", response_class=HTMLResponse)
    def selects_view():
        return selects_page()

    @app.get("/official", response_class=HTMLResponse)
    def official_view():
        return official_page()

    @app.post("/api/select")
    def api_select(body: dict):
        return {"select": guard(set_select, body.get("key"), body.get("verdict"),
                                body.get("branch", ""))}

    @app.get("/api/open")
    def api_open(key: str):
        d = select_dir((key or "").partition("/")[2])
        if d is None:
            raise HTTPException(status_code=404, detail="not in Selects")
        os.startfile(str(d))
        return {"opened": str(d)}

    def rot_for(key, sel):
        d = select_dir((key or "").partition("/")[2]) if sel else None
        return d / "rotations" if d and (d / "rotations" / "south.png").exists() else unit_rotations(key)

    @app.get("/still")
    def api_still(key: str, sel: int = 0):
        png = guard(lambda: still(rot_for(key, sel), max(1, scale - 1)))
        return Response(png, media_type="image/webp",
                        headers={"Cache-Control": "no-store"})

    @app.get("/turn")
    def api_turn(key: str, sel: int = 0):
        webp = guard(lambda: turnaround(rot_for(key, sel), max(1, scale - 1)))
        return Response(webp, media_type="image/webp",
                        headers={"Cache-Control": "no-store"})

    @app.post("/api/roster/field")
    def api_field(body: dict):
        return {"unit": guard(rs.set_field, body.get("key"), body.get("field"),
                              body.get("value"), body.get("title"))}

    @app.post("/api/roster/note")
    def api_note(body: dict):
        return {"notes": guard(rs.add_note, body.get("key"), body.get("text"))}

    @app.post("/api/roster/concept")
    def api_concept(body: dict):
        return {"key": guard(rs.add_concept, body.get("slug"), body.get("title"),
                             body.get("group"), body.get("expectation"))}

    @app.post("/api/generate")
    def api_generate(body: dict):
        slug = check_slug((body.get("slug") or "").strip())
        base_id = (body.get("base_id") or "").strip()
        if not base_id:
            raise HTTPException(400, "no base character id")
        count = max(1, min(8, int(body.get("count") or 1)))
        seed = body.get("seed")
        seed = int(seed) if str(seed or "").strip().lstrip("-").isdigit() else None
        tail = body.get("tail", TAIL)
        # Re-rolls of one description get -a/-b/-c, so the slug still names the folder and
        # the state, and two candidates for the same idea never collide.
        slugs = [slug] if count == 1 else \
            ["%s-%s" % (slug, chr(ord("a") + i)) for i in range(count)]
        queued = []
        for i, s in enumerate(slugs):
            guard(start_state, family, base_id, s, body.get("edit"), tail,
                  None if seed is None else seed + i)
            queued.append(s)
        return {"queued": queued}

    @app.get("/api/jobs")
    def api_jobs():
        completed = guard(poll, family)
        return {"completed": completed, "jobs": list(load_jobs(family).values())}

    @app.get("/rot/{slug}.png")
    def api_rot(slug: str):
        png = guard(rotation_strip, family, slug, scale)
        return Response(png, media_type="image/png",
                        headers={"Cache-Control": "no-store"})

    @app.post("/api/refine")
    def api_refine(body: dict):
        return guard(refine, family, (body.get("slug") or "").strip(), body.get("note"))

    @app.post("/api/verdict")
    def api_verdict(body: dict):
        return {"owner": guard(set_verdict, family, body.get("slug"),
                               body.get("verdict"), body.get("note", ""))}

    @app.post("/api/ship")
    def api_ship(body: dict = None):
        return JSONResponse(guard(ship, family, atlas, prefix))

    return app


