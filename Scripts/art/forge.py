# ---------------------------------------------------------------- PixelLab REST
#
# variantpipe.py's header says PixelLab's generators are MCP tools and this project calls
# them through the agent. That is true of variantpipe and stays true. Forge is the local
# app the owner drives alone: it has no MCP client and no agent, so it talks to the v2 REST
# API the same service exposes. Endpoints and field names below are pinned against
# https://api.pixellab.ai/v2/openapi.json, not guessed.

def _find_bearer(obj):
    """The pixellab MCP server's Authorization header, wherever it is nested.

    ~/.claude.json keys mcpServers under each project path, so the block sits several
    levels down and its depth is not something to hardcode.
    """
    if isinstance(obj, dict):
        pl = obj.get("pixellab")
        if isinstance(pl, dict):
            auth = (pl.get("headers") or {}).get("Authorization", "")
            if auth.lower().startswith("bearer "):
                return auth[7:].strip()
        for v in obj.values():
            hit = _find_bearer(v)
            if hit:
                return hit
    elif isinstance(obj, list):
        for v in obj:
            hit = _find_bearer(v)
            if hit:
                return hit
    return None


def api_key():
    """Env first, then the MCP config. Never read from or written to the repo."""
    k = os.environ.get("PIXELLAB_API_KEY")
    if k:
        return k.strip()
    cfg = Path.home() / ".claude.json"
    if cfg.exists():
        try:
            k = _find_bearer(json.loads(cfg.read_text(encoding="utf-8")))
        except (json.JSONDecodeError, UnicodeDecodeError):
            k = None
        if k:
            return k
    raise Fail("no PixelLab key: set PIXELLAB_API_KEY, or leave the pixellab MCP server "
               "configured in %s" % cfg)


def pl(method, path, body=None, timeout=90):
    data = json.dumps(body).encode("utf-8") if body is not None else None
    req = Request(API + path, data=data, method=method, headers={
        "Authorization": "Bearer " + api_key(),
        "Content-Type": "application/json",
        "User-Agent": UA,
    })
    try:
        with urlopen(req, timeout=timeout) as resp:
            return json.loads(resp.read().decode("utf-8") or "{}")
    except HTTPError as e:
        detail = e.read().decode("utf-8", "replace")[:400]
        raise Fail("PixelLab %s %s -> %s %s: %s" % (method, path, e.code, e.reason, detail))
    except URLError as e:
        raise Fail("PixelLab %s %s unreachable: %s" % (method, path, e.reason))


def balance():
    """(generations remaining, raw).

    `subscription.generations` is the REMAINING count, not the spent one -- measured
    2026-08-08 against get_balance's own "generations_remaining: 6083" while /balance
    returned {"generations": 6083.35, "total": 10000.0}. Read defensively anyway: the
    OpenAPI spec only $refs a Subscription schema, so the field names are not pinned by
    contract and a rename must dim the number, not break the page.
    """
    raw = pl("GET", "/balance", timeout=20)
    sub = raw.get("subscription") or {}
    for key in ("generations", "generations_remaining", "remaining"):
        if isinstance(sub.get(key), (int, float)):
            return int(sub[key]), raw
    return None, raw


# ---------------------------------------------------------------- prompt composition

def compose(edit, tail=TAIL):
    """The exact string sent as edit_description.

    Deterministic and from named parts, the same discipline as pixelpipe.compose_prompt --
    create_character_state takes no seed by default, so a recorded composition is the only
    thing that makes a state reproducible. Unlike pixelpipe's composer this appends NO
    palette clause and no house negatives: those exist to fight a 4-value ramp that was
    superseded 2026-07-28, and the base character's own palette is inherited through
    use_color_palette_from_reference instead.
    """
    edit = (edit or "").strip().rstrip(".").strip()
    if not edit:
        raise Fail("edit description is empty")
    tail = (tail or "").strip()
    return ("%s. %s" % (edit, tail)).strip() if tail else "%s." % edit


def check_slug(slug):
    if not SLUG_RE.match(slug or ""):
        raise Fail("'%s' is not a slug. Use kebab-case: lowercase letters, digits and "
                   "single hyphens (e.g. 'turret-nest'). This field is what stops the "
                   "account filling up with names like 'Can you make a Turre'." % slug)
    return slug


# ---------------------------------------------------------------- family + job state

def forge_block(family):
    """The optional "forge" block in family.json. Every field is optional; CLI flags win."""
    try:
        return (vp.load_spec(family).get("forge") or {})
    except Fail:
        return {}


def jobs_path(family):
    return vp.RENDERS / family / "forge-jobs.json"


def load_jobs(family):
    p = jobs_path(family)
    return vp.load_json(p) if p.exists() else {}


def save_jobs(family, jobs):
    # On disk, not just in memory: a state costs 20-40 generations and takes minutes, so
    # losing the character_id to a restart would strand spend with no way back to the art.
    vp.save_json(jobs_path(family), jobs)


def rotations_dir(family, slug):
    root = vp.raw_root(family)
    for name, d in sr.variant_dirs(root):
        if name == slug:
            return d
    raise Fail("no rotations on disk for '%s' under %s" % (slug, root))


def rotations_rel(family, slug):
    """Repo-relative rotations dir for a variant, in the form atlas.py --rotations wants."""
    return str(rotations_dir(family, slug).relative_to(REPO)).replace("\\", "/")


def slugify(s):
    s = re.sub(r"[^a-z0-9]+", "-", (s or "").lower()).strip("-")
    return s or "variant"


def character_id_of(family, slug):
    """The PixelLab character this variant IS -- the thing a refinement edits.

    Three places record it, in descending order of directness. The last two exist because
    most of what is on disk predates forge: pathfinder-line's twelve were an owner-supplied
    group download, and their ids live in the family's own naming map and in the group's
    source.json rather than in any job forge ran.
    """
    j = load_jobs(family).get(slug) or {}
    if j.get("character_id"):
        return j["character_id"]
    try:
        spec = vp.load_spec(family)
    except Fail:
        spec = {}
    for e in ((spec.get("naming") or {}).get("map") or []):
        if slug in (e.get("folder"), e.get("slug")) and e.get("state_id"):
            return e["state_id"]
    src = vp.RENDERS / family / "source.json"
    if src.exists():
        got = (vp.load_json(src).get("state_ids") or {}).get(slug)
        if got:
            return got
    raise Fail("no PixelLab character id recorded for '%s', so there is nothing to refine "
               "from. Its id is not in forge-jobs.json, family.json's naming.map, or "
               "source.json -- generate a fresh variant off the base instead." % slug)


def next_refine_slug(family, slug):
    """<slug>-r2, -r3, ... skipping anything already on disk or already queued."""
    stem = re.sub(r"-r\d+$", "", slugify(slug))
    taken = set(load_jobs(family))
    root = vp.raw_root(family)
    if root.exists():
        taken |= {n for n, _ in sr.variant_dirs(root)}
    n = 2
    while "%s-r%d" % (stem, n) in taken:
        n += 1
    return "%s-r%d" % (stem, n)


# ---------------------------------------------------------------- generate + poll

def start_state(family, base_id, slug, edit, tail=TAIL, seed=None, extra=None):
    check_slug(slug)
    jobs = load_jobs(family)
    if slug in jobs and jobs[slug].get("status") != "failed":
        raise Fail("'%s' already has a job (%s). Pick another slug."
                   % (slug, jobs[slug].get("status")))
    if slug in dict(sr.variant_dirs(vp.raw_root(family)) if vp.raw_root(family).exists() else []):
        raise Fail("'%s' already has renders on disk -- pick another slug" % slug)

    prompt = compose(edit, tail)
    body = {
        "character_id": base_id,
        "edit_description": prompt,
        "state_name": slug,                        # the whole point; see module docstring
        "use_color_palette_from_reference": True,  # cohesion with the base, not the ramp
    }
    if seed is not None:
        body["seed"] = int(seed)

    resp = pl("POST", "/create-character-state", body)
    jobs[slug] = {
        "slug": slug, "base_id": base_id,
        "character_id": resp["character_id"],
        "background_job_id": resp.get("background_job_id"),
        "edit": edit, "tail": tail, "prompt": prompt, "seed": seed,
        "usage": resp.get("usage"), "started": vp.now(), "status": "pending",
    }
    jobs[slug].update(extra or {})
    save_jobs(family, jobs)
    return jobs[slug]


# A refine is a correction, not a new idea, so its tail is the opposite of TAIL's: TAIL
# tells the model what to hold while it invents a variant, this tells it to invent nothing.
REFINE_TAIL = ("Change only what is described and nothing else. Keep the same character, "
               "pose, proportions and kit. Match the existing color palette exactly, no "
               "new colors, no glowing parts.")


def refine(family, slug, note, tail=REFINE_TAIL):
    """Generate a corrected candidate FROM this variant, not from the family base.

    A refinement's parent is the variant's own character, so the fix inherits everything
    already approved about it and only the named defect moves. Editing the base instead
    would throw away every earlier step.

    The note is logged on the PARENT's manifest entry whether or not the child ever lands.
    A defect worth describing is a finding about that sprite, and it survives the child
    being rejected.

    WHAT THIS CANNOT DO: fix a named rotation. A state edit re-renders the whole character,
    so "the shield drifts off to the side in north-east" moves nothing -- measured
    2026-08-08 on pavisewall, where the three rotations the note named came back
    byte-identical and the two that did change got worse (PIXELLAB-MCP.md). Refine changes
    what the subject IS. Per-facing geometry needs the anchor-and-rotate path.
    """
    note = (note or "").strip()
    if not note:
        raise Fail("say what needs cleaning up")
    parent = character_id_of(family, slug)
    child = next_refine_slug(family, slug)

    man = vp.load_manifest(family)
    man["family"] = family
    v = man.setdefault("variants", {}).setdefault(slug, {})
    v.setdefault("refine_notes", []).append(
        {"at": vp.now(), "note": note, "child": child})
    vp.save_json(vp.manifest_path(family), man)

    start_state(family, parent, child, note, tail,
                extra={"refined_from": slug, "refine_note": note})
    return {"queued": [child], "parent": slug, "parent_character_id": parent}


def rotation_strip(family, slug, scale=3):
    """All 8 rotations in one PNG, in sr.DIRECTIONS order.

    The card shows south, but the defects worth refining are usually the ones a south-only
    view cannot show -- a prop that survives facing the camera and vanishes from behind.
    silhouette_report says the same thing about judging; this is the same rule applied to
    describing a fix.
    """
    from PIL import Image
    d = rotations_dir(family, slug)
    ims = [Image.open(d / ("%s.png" % dirn)).convert("RGBA")
           for dirn in sr.DIRECTIONS if (d / ("%s.png" % dirn)).exists()]
    if not ims:
        raise Fail("no rotations on disk for '%s'" % slug)
    gap = 2
    w = sum(i.width for i in ims) * scale + gap * (len(ims) - 1)
    h = max(i.height for i in ims) * scale
    out = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    x = 0
    for i in ims:
        r = i.resize((i.width * scale, i.height * scale), Image.NEAREST)
        out.alpha_composite(r, (x, h - r.height))
        x += r.width + gap
    buf = __import__("io").BytesIO()
    out.save(buf, "PNG")
    return buf.getvalue()


def turnaround(rot_dir, scale=2, ms=140):
    """The eight rotations as one looping animated WebP -- the unit turning on the spot.

    A still strip makes you compare eight things; a turnaround makes a break in the cycle
    jump out on its own, which is the whole problem with judging rear facings. Frames are
    padded to a common canvas and bottom-aligned so the figure does not bob: rotations are
    cropped to their own content and a naive paste would make the sprite hop every frame.
    Lossless, because these are flat-palette pixels and WebP's lossy mode invents colours
    at exactly the edges the silhouette is judged on.
    """
    from PIL import Image
    ims = [Image.open(rot_dir / ("%s.png" % d)).convert("RGBA")
           for d in sr.DIRECTIONS if (rot_dir / ("%s.png" % d)).exists()]
    if not ims:
        raise Fail("no rotations to animate in %s" % rot_dir)
    w = max(i.width for i in ims) * scale
    h = max(i.height for i in ims) * scale
    frames = []
    for i in ims:
        r = i.resize((i.width * scale, i.height * scale), Image.NEAREST)
        f = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        f.alpha_composite(r, ((w - r.width) // 2, h - r.height))
        frames.append(f)
    buf = __import__("io").BytesIO()
    frames[0].save(buf, "WEBP", save_all=True, append_images=frames[1:],
                   duration=ms, loop=0, lossless=True, minimize_size=True)
    return buf.getvalue()


def poll(family):
    """Advance every pending job. Returns the number that completed this pass.

    Polls GET /characters/{id} rather than the background job: the character carries both
    the terminal status AND rotation_urls, so one call answers "done?" and "where are the
    PNGs?" without depending on the job-status string enum, which the spec leaves open.
    """
    jobs = load_jobs(family)
    done = 0
    for slug, j in jobs.items():
        if j.get("status") != "pending":
            continue
        try:
            d = pl("GET", "/characters/%s" % j["character_id"], timeout=30)
        except Fail as e:
            j["last_error"] = str(e)
            continue
        j.pop("last_error", None)
        status = (d.get("status") or "").lower()
        rot = d.get("rotation_urls") or {}
        if status in ("failed", "error"):
            j["status"] = "failed"
            j["error"] = d.get("error") or status
            continue
        if status != "completed" or not rot:
            continue
        urls = [rot[k] for k in sr.DIRECTIONS if rot.get(k)]
        if len(urls) < len(sr.DIRECTIONS):
            # Judge rejects a variant missing rotations outright, so landing a partial set
            # would just manufacture a reject. Wait for the rest instead.
            continue
        # variantpipe owns downloading and the urls/fetched/files manifest entry; calling
        # its command keeps one implementation of the CDN's User-Agent and zip handling.
        vp.cmd_fetch(SimpleNamespace(family=family, variant=slug, url=urls))
        size = d.get("size") or {}
        j.update(status="done", fetched=vp.now(),
                 canvas=[size.get("width"), size.get("height")],
                 pixellab_name=d.get("name"), group_id=d.get("group_id"))
        done += 1
    save_jobs(family, jobs)
    return done


# ---------------------------------------------------------------- verdicts

def set_verdict(family, slug, verdict, note=""):
    """Write the owner's call into manifest.json under a key judge never touches.

    `verdict` there is variantpipe's MEASUREMENT verdict (keep/flag/reject) and gets
    overwritten every time judge runs. The human call goes in a sibling `owner` block so
    the two can disagree -- which is the useful case: a variant judge rejects as
    mechanically redundant can still be the one that reads best in a crowd.

    Approving also copies the generation record out of forge-jobs.json and into the same
    block, which is what makes the variant reproducible: create_character_state accepts no
    seed by default, so the composed prompt plus the base id IS the recipe.

    That record goes in the manifest and NOT into family.json's variants[], even though
    that array is the nominal home for a state's recipe. vp.save_json rewrites a whole file
    with json.dump, and family.json is hand-maintained with compact inline arrays -- so
    appending one variant reformats ~200 lines and buries the real change. The manifest is
    machine-written and already expanded, so it costs nothing there. `ship` prints the
    family.json line to paste if the owner wants `variantpipe.py plan` to replay it.
    """
    if verdict not in ("approve", "deny", "clear"):
        raise Fail("verdict must be approve, deny or clear (got %r)" % verdict)
    man = vp.load_manifest(family)
    man["family"] = family
    v = man.setdefault("variants", {}).setdefault(slug, {})
    if verdict == "clear":
        v.pop("owner", None)
    else:
        owner = v.setdefault("owner", {})
        owner.update(verdict=verdict, at=vp.now(), note=note or "")
        owner.setdefault("shipped", None)
        job = load_jobs(family).get(slug)
        if job and verdict == "approve":
            owner["generated"] = {
                "base_id": job.get("base_id"),
                "character_id": job.get("character_id"),
                "edit_description": job.get("prompt"),
                "seed": job.get("seed"),
                "tool": "forge.py create-character-state",
            }
    vp.save_json(vp.manifest_path(family), man)
    return v.get("owner")


def owner_of(man, slug):
    return ((man.get("variants") or {}).get(slug) or {}).get("owner") or {}


def spec_line(family, slug):
    """The family.json variants[] entry for an approved variant, as pasteable JSON.

    Printed rather than written, for the formatting reason in set_verdict's docstring.
    Paste it in and `variantpipe.py plan` can replay the state from the spec alone.
    """
    owner = owner_of(vp.load_manifest(family), slug)
    gen = owner.get("generated") or {}
    if not gen.get("edit_description"):
        return None
    return json.dumps({"slug": slug, "edit_description": gen["edit_description"],
                       "source": "generated"}, ensure_ascii=False)


# ---------------------------------------------------------------- ship

def run(cmd, cwd=REPO):
    p = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True)
    return {"cmd": " ".join(str(c) for c in cmd), "rc": p.returncode,
            "out": (p.stdout or "") + (p.stderr or "")}


def ue_import(request_id):
    """Import through the running editor, via the MCP driver Scripts/ue-mcp-call.py.

    Deliberately not a hand-rolled HTTP call: that script already speaks the meta-server's
    held-open-SSE protocol. If the editor is down this fails softly -- the sheet on disk is
    still correct and the import can be run later, so it must not fail the whole batch.
    """
    script = (REPO / "Scripts" / "art" / "import_sprites.py").as_posix()
    args = json.dumps({"Command": 'py "%s" %s' % (script, request_id)})
    r = run([sys.executable, str(REPO / "Scripts" / "ue-mcp-call.py"),
             "call", "Exec", args, "KindledConsoleToolset"])
    if r["rc"] != 0:
        r["out"] += ("\nEditor not reachable. The sheet is packed and correct; run this "
                     "in the editor when it is up:\n  py Scripts/art/import_sprites.py %s"
                     % request_id)
    return r


def ship(family, atlas, prefix):
    """Promote every approved-but-unshipped variant, once, as a batch.

    A batch and not an approve side-effect because an atlas row is not a pure data change:
    it needs a SwarmFragments.h constant bumped (a recompile) and the Niagara emitter's
    Sub UV widened. atlas.py prints both numbers and deliberately edits neither. Batching
    means one recompile per session instead of one per unit.
    """
    man = vp.load_manifest(family)
    todo = sorted(s for s, v in (man.get("variants") or {}).items()
                  if (v.get("owner") or {}).get("verdict") == "approve"
                  and not (v.get("owner") or {}).get("shipped"))
    if not todo:
        return {"shipped": [], "log": [], "note": "nothing approved and unshipped"}
    if not atlas or not prefix:
        raise Fail("ship needs an atlas request id and a prefix. Pass --atlas/--prefix, or "
                   'add "forge": {"atlas": "team-units", "prefix": "archer-"} to '
                   "docs/data/art/families/%s/family.json" % family)

    atlas_py = str(REPO / "Scripts" / "art" / "atlas.py")
    log, added = [], []
    for slug in todo:
        r = run([sys.executable, atlas_py, "add", atlas,
                 "--prefix", prefix + slug, "--rotations", rotations_rel(family, slug)])
        log.append(r)
        if r["rc"] == 0:
            added.append(slug)
    if added:
        log.append(run([sys.executable, str(REPO / "Scripts" / "art" / "pixelpipe.py"),
                        "pack", atlas]))
        log.append(ue_import(atlas))
    log.append(run([sys.executable, atlas_py, "check", "--all"]))

    man = vp.load_manifest(family)
    for slug in added:
        owner = man.setdefault("variants", {}).setdefault(slug, {}).setdefault("owner", {})
        owner["shipped"] = vp.now()
        owner["atlas_prefix"] = prefix + slug
    vp.save_json(vp.manifest_path(family), man)

    lines = [ln for ln in (spec_line(family, s) for s in added) if ln]
    if lines:
        log.append({"cmd": "(paste into docs/data/art/families/%s/family.json variants[] "
                           "so variantpipe.py plan can replay these)" % family,
                    "rc": 0, "out": ",\n".join(lines)})
    return {"shipped": added, "log": log}


# ---------------------------------------------------------------- measurement for cards

def nearest_sibling(bands, name, only=None):
    """(closest name, distance) on the three band midpoints.

    Variety is the question this page exists to answer, and the honest form of it is not
    "how far is this from the base" but "how close is this to whatever it most resembles" --
    a family fails when any two members collapse together, wherever they sit relative to
    the base. Distance is on band midpoints so a directional form is compared on its whole
    rotation range, not on its south frame (silhouette_report's own warning).
    """
    b = bands.get(name) or {}
    if b.get("missing"):
        return None, None
    def mid(x, k):
        return (x[k][0] + x[k][1]) / 2.0
    best, bestd = None, None
    for other, ob in bands.items():
        if other == name or ob.get("missing"):
            continue
        if only is not None and other not in only:
            continue
        d = sum(abs(mid(b, k) - mid(ob, k)) for k in ("aspect", "solidity", "asymmetry"))
        if bestd is None or d < bestd:
            best, bestd = other, d
    return best, bestd


def cards(family):
    """[(name, measure_dict)] with judge's verdict, the owner's verdict and the two
    nearest-neighbour numbers stamped on. judge_family is variantpipe's -- this adds the
    owner layer on top rather than re-deriving any measurement."""
    rows, verdicts, spec = vp.judge_family(family)
    bands = {n: verdicts[n]["band"] for n, _ in rows}
    man = vp.load_manifest(family)
    jobs = load_jobs(family)
    approved = {s for s, _ in rows if owner_of(man, s).get("verdict") == "approve"}

    out = []
    for name, m in sorted(rows, key=lambda kv: kv[0]):
        m["verdict"] = verdicts[name]["verdict"]
        m["reasons"] = verdicts[name]["reasons"]
        m["owner"] = owner_of(man, name)
        m["job"] = jobs.get(name)
        m["refine_notes"] = ((man.get("variants") or {}).get(name) or {}).get("refine_notes")
        m["near"], m["near_d"] = nearest_sibling(bands, name)
        m["near_ok"], m["near_ok_d"] = nearest_sibling(bands, name, only=approved - {name})
        m["band"] = bands.get(name) or {}
        out.append((name, m))
    return out, spec


