"""Sprite Forge -- a local page for making units without a Claude session in the loop.

WHY THIS EXISTS
---------------
Making a new unit used to cost a conversation: /variants emitted create_character_state
kwargs for the agent to run over MCP, the agent fetched the rotations, ran
silhouette_report, published a static HTML sheet as an artifact, the owner said "keep 2, 5,
7" in chat, and a second skill packed and imported. Four handoffs, all through the agent,
and the owner's actual keep/cull call was never recorded anywhere a machine could read --
only judge's MEASUREMENT verdict (keep/flag/reject) landed in the manifest.

So this is the same pipeline with the agent made optional:

    prompt -> candidates -> measured contact sheet -> approve/deny -> atlas + Unreal

It owns none of the pipeline. Measurement is silhouette_report's, judging and the family
contract are variantpipe's, atlas rows are atlas.py's, packing is pixelpipe's, importing is
import_sprites.py's. What is new here is exactly three things: an HTTP surface, a REST
client for PixelLab (variantpipe deliberately has none -- see its header), and the
`variants.<slug>.owner` block, which is the first structured record of a human verdict in
this repo.

    py Scripts/art/forge.py --family pathfinder-line
    py Scripts/art/forge.py --family knight-melee-v2 --port 8770 --no-open
    py Scripts/art/forge.py --selftest

THE SLUG IS THE POINT
---------------------
The PixelLab account holds 158 characters, ~135 of them states named from truncated raw
prompts -- "Can you make a Turre", "Reshape this creatur" x5, "make one of stone". That
happened because create_character_state's `state_name` was never sent, so the service fell
back to the prompt. Forge requires a kebab-case slug and always sends it. It cannot fix the
135 already up there; it stops the 136th.

BOTH GENERATION PATHS, ONE CODE PATH
------------------------------------
`/` rescans RawArt/Renders/<family>/raw/ on every load. A variant generated here and one
generated by the agent over MCP and landed with `variantpipe.py fetch` are the same thing on
disk, so both appear with no sync step and no second reader.

PALETTE
-------
Full colour, no quantize -- docs/art/aesthetic-direction.md's 2026-07-28 amendment. Forge
never calls `pixelpipe.py quantize`, and atlas.py already defaults quantize:false.
`use_color_palette_from_reference` stays on because that is cohesion with the base
character, not the retired 4-value ramp.
"""

