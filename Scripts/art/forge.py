def unit_rotations(key):
    """The rotations dir for a roster key.

    Resolved from the key's own shape rather than by searching a built roster: every
    thumbnail and turnaround on the page calls this, and rs.build() walks every family,
    every request and both atlases. One image request must not cost a full inventory.
    """
    kind, _, rest = (key or "").partition("/")
    if not rest:
        raise Fail("bad roster key %r" % key)

    if kind == "shipped":
        d = (vp.RENDERS / rest).resolve()
    elif kind == "request":
        req_path = rs.REQUESTS / ("%s.json" % rest)
        if not req_path.exists():
            raise Fail("no request '%s'" % rest)
        req = vp.load_json(req_path)
        rev = vp.RENDERS / rest / ("r%d" % req.get("revision", 1))
        d = next((c for c in (rev / "raw" / "rotation", rev / "quantized" / "rotation")
                  if (c / "south.png").exists()), None)
    elif kind == "concept":
        raise Fail("'%s' has no art yet" % key)
    else:                                   # "<family>/<slug>"
        root = vp.raw_root(kind)
        d = dict(sr.variant_dirs(root)).get(rest) if root.exists() else None

    if d is None or not (Path(d) / "south.png").exists():
        raise Fail("no rotations on disk for '%s'" % key)
    return Path(d)


def still(rot_dir, scale=2):
    """The south frame alone, for the roster's row thumbnail."""
    from PIL import Image
    im = Image.open(rot_dir / "south.png").convert("RGBA")
    im = im.resize((im.width * scale, im.height * scale), Image.NEAREST)
    buf = __import__("io").BytesIO()
    im.save(buf, "WEBP", lossless=True)
    return buf.getvalue()


